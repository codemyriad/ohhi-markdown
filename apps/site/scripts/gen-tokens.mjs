#!/usr/bin/env node
/**
 * gen-tokens — the landing site's colours ARE the app's.
 *
 * Reads @ohhi/ui's default theme pair (tokens/editor-light.css and
 * tokens/editor-dark.css) and the token contract (tokens/_contract.css), and
 * writes src/styles/tokens.generated.css: the subset of band A (the DaisyUI
 * chrome tokens) and band B (--ed-*) this site reads, as plain custom
 * properties. Light on :root; dark under prefers-color-scheme and under
 * [data-theme="editor-dark"], the attribute the app itself hangs a theme on.
 * No Tailwind and no DaisyUI here: the site is static CSS.
 *
 *   node scripts/gen-tokens.mjs          # write the file
 *   node scripts/gen-tokens.mjs --check  # exit 1 if the committed file is stale
 *
 * A token listed below but missing from a theme is an error, not a default:
 * the app's theme-contract.test.ts owns the contract; this script only
 * follows it. Add a token here when a stylesheet starts reading it.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../src/styles/tokens.generated.css')

/** Band A — DaisyUI's chrome tokens, from the `@plugin "daisyui/theme"` block. */
const CHROME = [
  '--color-base-100',
  '--color-base-200',
  '--color-base-300',
  '--color-base-content',
  '--color-primary',
  '--color-primary-content',
  '--color-secondary',
  '--color-accent',
  '--radius-field',
  '--radius-box',
]
/** Band B — the editor tokens, from the `[data-theme="…"]` block. */
const EDITOR = [
  '--ed-surface',
  '--ed-ink',
  '--ed-ink-muted',
  '--ed-ink-faint',
  '--ed-h1',
  '--ed-h2',
  '--ed-h3',
  '--ed-title',
  '--ed-link',
  '--ed-link-hover',
  '--ed-code-fg',
  '--ed-code-bg',
  '--ed-code-border',
  '--ed-hr',
  '--ed-tag-fg',
  '--ed-tag-bg',
  '--ed-selection',
  '--ed-caret',
  '--ed-mark-bg',
  '--ed-mark-fg',
  '--ed-quote-border',
  '--ed-bullet',
]
/** Polarity-independent: the faces and metrics, from the contract's `:root`. */
const CONTRACT = [
  '--ed-font-prose',
  '--ed-font-mono',
  '--ed-font-ui',
  '--ed-font-size',
  '--ed-line-height',
  '--ed-measure',
]

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '')

/** The text between the braces of the first block that starts with `opener`. */
function block(css, opener, file) {
  const start = css.indexOf(opener)
  if (start < 0) throw new Error(`${file}: no "${opener}" block`)
  const open = css.indexOf('{', start)
  let depth = 0
  for (let j = open; j < css.length; j++) {
    if (css[j] === '{') depth++
    else if (css[j] === '}' && --depth === 0) return css.slice(open + 1, j)
  }
  throw new Error(`${file}: unbalanced "${opener}" block`)
}

function decls(text) {
  const out = new Map()
  for (const m of text.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out.set(m[1], m[2].trim())
  return out
}

function pick(map, names, file, indent = '  ') {
  const missing = names.filter((n) => !map.has(n))
  if (missing.length) throw new Error(`${file}: missing ${missing.join(', ')}`)
  return names.map((n) => `${indent}${n}: ${map.get(n)};`).join('\n')
}

function read(name) {
  const file = require.resolve(`@ohhi/ui/styles/tokens/${name}.css`)
  return { file, css: stripComments(readFileSync(file, 'utf8')) }
}

function theme(name, indent) {
  const { file, css } = read(name)
  const chromeBlock = block(css, '@plugin "daisyui/theme"', file)
  const scheme = /color-scheme:\s*(light|dark)\s*;/.exec(chromeBlock)?.[1]
  if (!scheme) throw new Error(`${file}: the daisyui/theme block names no color-scheme`)
  const chrome = decls(chromeBlock)
  const editor = decls(block(css, `[data-theme="${name}"]`, file))
  const body = [
    `${indent}color-scheme: ${scheme};`,
    pick(chrome, CHROME, file, indent),
    pick(editor, EDITOR, file, indent),
  ].join('\n')
  return { scheme, body }
}

const contract = read('_contract')
const light = theme('editor-light', '  ')
const dark = theme('editor-dark', '    ')
const darkFlat = theme('editor-dark', '  ')
if (light.scheme !== 'light' || dark.scheme !== 'dark') {
  throw new Error(`expected editor-light to be light and editor-dark to be dark, got ${light.scheme}/${dark.scheme}`)
}

const output = `/*
 * GENERATED by scripts/gen-tokens.mjs from @ohhi/ui — do not hand-edit.
 * Sources: libs/ui/src/styles/tokens/_contract.css, editor-light.css,
 * editor-dark.css. \`rushx gen-tokens\` rewrites it; \`rushx check\` fails
 * when it is stale.
 */

/* The contract: faces and metrics, the same in both polarities. */
:root {
${pick(decls(block(contract.css, ':root', contract.file)), CONTRACT, contract.file)}
}

/* Oh Hi Light — the default. */
:root,
[data-theme="editor-light"] {
${light.body}
}

/* Oh Hi Dark — the OS's choice, unless the page pins light. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="editor-light"]) {
${dark.body}
  }
}

[data-theme="editor-dark"] {
${darkFlat.body}
}
`

const rel = relative(process.cwd(), OUT)
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing counts as stale */
  }
  if (current !== output) {
    console.error(`${rel} is stale: run \`rushx gen-tokens\` (cd apps/site) and commit the result`)
    process.exit(1)
  }
  console.log(`${rel} is current`)
} else {
  writeFileSync(OUT, output)
  console.log(`wrote ${rel}`)
}
